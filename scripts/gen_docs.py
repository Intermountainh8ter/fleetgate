def targets() -> dict[Path, str]:
    out = {
        DOCS / "RUNBOOKS.md": runbooks_md() + "\n",
        DOCS / "SCENARIOS.md": scenarios_md() + "\n",
        DOCS / "POLICY.md": policy_md() + "\n",
        DOCS / "FLOWCHARTS.md": flowcharts_md() + "\n",
    }
    for path in [ROOT / "README.md", *sorted((DOCS / "launch").glob("*.md"))]:
        if path.exists():
            out[path] = render_markers(path.read_text(), path.name)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if any generated file is out of date")
    a = ap.parse_args(argv)
    stale = []
    for path, new in targets().items():
        old = path.read_text() if path.exists() else None
        if old != new:
            stale.append(path.relative_to(ROOT).as_posix())
            if not a.check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(new)
    if a.check:
        if stale:
            print("stale generated docs (run: python scripts/gen_docs.py): " + ", ".join(stale))
            return 1
        print("generated docs are up to date")
        return 0
    print("updated: " + (", ".join(stale) if stale else "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
