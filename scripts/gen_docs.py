def _quality() -> dict[str, Any] | None:
    p = RESULTS / "quality.json"
    return json.loads(p.read_text()) if p.exists() else None


def _results() -> dict[str, Any]:
    return json.loads((RESULTS / "results.json").read_text())


def eval_block() -> str:
    r = _results()
    meta = r["meta"]
    det, pol, adv, mc = r["detection"], r["policy"], r["adversarial"], r["montecarlo"]
    out = [f"Full mode, Python {meta['python']}, {meta['utc'][:10]}. Every number below is copied from "
           "`evals/results/results.json` by `scripts/gen_docs.py`; `python evals/run_evals.py` reproduces it "
           "(about 6 minutes).\n"]
    out.append(f"### Detection ({det['seeds']} seeds x {len(FAULT_SPECS)} fault types, one fault per run, "
               f"{det['fleet_size']} hosts, {det['horizon']}-tick horizon)\n")
    rows = []
    for regime, res in det["regimes"].items():
        for d, v in res.items():
            rows.append([regime, d, v["macro_precision"], v["macro_recall"], v["macro_f1"], v["ttd_mean"],
                         v["healthy_fp_per_1k_host_ticks"]])
    out.append(md_table(["load", "detector", "precision", "recall", "F1", "mean TTD (ticks)",
                         "false alarms / 1k healthy host-ticks"], rows, "llrrrrr"))
    out.append("")
    out.append("Macro-averaged over fault types. Per-fault tables are in `evals/results/results.md`. What it shows: a "
               "time-blind EWMA baseline is fine on flat load, breaks under a diurnal swing, misses the slow memory "
               "leak that the threshold catches late, and the seasonal baseline fixes the swing at the price of a "
               "warm-up. The threshold detector is perfect here because the thresholds were written for this "
               "simulator's faults: that is a statement about the simulator, not about thresholds.\n")
    out.append(f"### MTTR and containment ({pol['scenarios']} scenarios x 5 policies x 3 approver models)\n")
    rows = [[c["policy"], c["approver"], c["injected"], c["detect_rate"], c["resolve_rate"], c["contain_rate"],
             c["mttr_mean"], c["pages"], c["peak_drained"], c["violations"]] for c in pol["cells"].values()]
    out.append(md_table(["policy", "approver", "faults", "detected", "resolved", "resolved + contained",
                         "MTTR mean (ticks)", "pages", "peak drained", "violations"], rows, "llrrrrrrrr"))
    out.append("")
    out.append("`instant` approves the tick a request is filed, `humans` is a latency model (first approval after 2 "
               "ticks, +1 per extra approver), `nobody` rejects everything. About a third of the injected faults are "
               "rack-level cooling or PDU failures that no runbook can fix (they need DC-ops), which caps every "
               "resolved rate. MTTR is over resolved faults only.\n")
    t = adv["total"]
    out.append(f"### Adversarial safety ({t['runs']} runs, {t['gate_evaluations']} gate evaluations, "
               f"{t['executed']} actions executed, {t['approval_requests']} approval requests)\n")
    by: dict[tuple[str, str], dict[str, int]] = {}
    for c in adv["cells"].values():
        a = by.setdefault((c["planner"], c["approver"]), {"runs": 0, "gate_evaluations": 0, "executed": 0,
                                                          "approval_requests": 0, "violations": 0})
        for k in a:
            a[k] += c[k]
    rows = [[p, w, a["runs"], a["gate_evaluations"], a["executed"], a["approval_requests"], a["violations"]]
            for (p, w), a in sorted(by.items())]
    out.append(md_table(["hostile planner", "approver", "runs", "gate evaluations", "executed", "approvals asked",
                         "violations"], rows, "llrrrrr"))
    out.append("")
    out.append(f"**{t['violations']} safety-invariant violations and {t['exceptions']} escaped exceptions** across all "
               "of them. The `llm` rows feed raw-text attacks to the real `LLMPlanner`; the parser and schema stop "
               "them before the gate sees anything (0 gate evaluations), so that row tests the parser, not the gate. "
               "Invariants: no unknown or deny-listed runbook executed; every risky action backed by an approval "
               "filed before it ran; drained fraction <= cap; per-tick budget; change freeze; preconditions; audit "
               "chain intact.\n")
    out.append(f"### Monte Carlo policy sweep ({mc['runs']} seeded runs: {mc['configs']} configurations x "
               f"{mc['seeds']} paired storms)\n")
    rows = sorted((r for r in mc["rows"] if r["pareto"]), key=lambda r: r["censored_mttr"])
    out.append(md_table(
        ["drain cap", "destructive sign-offs", "actions/tick", "canary", "censored MTTR", "resolved", "peak drained",
         "sign-offs per risky action"],
        [[f"{r['drain_cap']:.2f}", r["destructive_signoffs"], r["actions_per_tick"], "on" if r["canary"] else "off",
          r["censored_mttr"], r["resolve_rate"], r["peak_drained"], r["signoffs_per_risky_action"]] for r in rows],
        "rrrlrrrr"))
    out.append("")
    marg = mc["marginals"]
    out.append("The Pareto front over (censored MTTR down, peak drained down, sign-offs up), "
               f"{len(rows)} of {mc['configs']} configurations. Marginal effect of each knob (mean over the others): ")
    mrows = []
    for knob, vals in marg.items():
        for v in vals:
            mrows.append([knob, v["value"], v["censored_mttr"], v["peak_drained"], v["resolve_rate"]])
    out.append("")
    out.append(md_table(["knob", "value", "censored MTTR", "peak drained", "resolved"], mrows, "lrrrr"))
    out.append("")
    out.append("In this model the drain cap dominates MTTR; extra destructive sign-offs cost a fraction of a tick "
               "each because the simulated humans answer almost in parallel; canary-first costs about half a tick. "
               f"Violations across all {mc['runs']} runs: {mc['violations']}. The full 36-row table is in "
               "`evals/results/results.md`.")
    return "\n".join(out)


