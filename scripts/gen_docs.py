def runbooks_md() -> str:
    tiers = {t: REGISTRY.by_tier(t) for t in Tier}
    out = [GENERATED_NOTE, "# Runbook catalogue\n",
           f"{len(CATALOG)} runbooks in {len(Tier)} risk tiers, loaded from `src/fleetgate/data/runbooks.json` and "
           "validated at import (unknown faults, unknown preconditions, a rollback riskier than its action, or a "
           "playbook naming a missing runbook all refuse to load).\n",
           "An agent can only *name* a runbook id from this list. Nothing an agent emits is executable: the runbook's "
           "effects are data interpreted by a handful of primitives (`clear_fault`, `clear_faults`, `set_state`, "
           "`clear_all_faults`) in `runbooks.py`.\n",
           "## Risk tiers\n",
           md_table(["tier", "meaning", "default gate decision", "runbooks"], [
               ["REVERSIBLE", "undo is cheap and complete (restart, bounce a NIC, drain, ticket)",
                "ALLOW on unprotected hosts; NEEDS_APPROVAL on protected roles", len(tiers[Tier.REVERSIBLE])],
               ["DISRUPTIVE", "interrupts service or takes time (reboot, rebuild, firmware, part swap)",
                "NEEDS_APPROVAL, unless a maintenance window covers the DC (unprotected hosts only)",
                len(tiers[Tier.DISRUPTIVE])],
               ["DESTRUCTIVE", "irreversible or loses data (replace disk, reimage, decommission, failover)",
                "NEEDS_APPROVAL always (N-of-M); never auto-allowed", len(tiers[Tier.DESTRUCTIVE])],
           ], "lllr"), "",
           "## Fields\n",
           "- **preconditions**: state the gate probes before allowing the runbook (`host_drained`, `ticket_open`, "
           "`bmc_reachable`, `ssh_reachable`, `role:<name>`, ...). A failed one is `DENY_PRECONDITION_FAILED`.\n"
           "- **verify**: probes the VerifierAgent re-reads after `duration_ticks + 1`. A failure proposes the "
           "**rollback** partner (through the gate like anything else) and pages a human.\n"
           "- **scope**: `host`, or `rack` (the runbook touches every host in the rack; the gate then judges *all* of "
           "them for protected roles and the drain cap).\n"
           "- **duration**: ticks until fault clears land; state changes (drain, ticket) land immediately.\n"
           "- **dry-run**: `fleetgate simulate --dry-run` evaluates and audits every step but mutates nothing.\n"]
    for tier in Tier:
        out.append(f"## {tier.name.title()} runbooks\n")
        rows = []
        for r in sorted(tiers[tier], key=lambda r: r.id):
            probes = "; ".join(p["metric"] + " " + p["op"] + " " + str(p["value"]) if "metric" in p
                               else f"{p['state']} == {p['equals']}" for p in r.verify) or "-"
            rows.append([code(r.id), r.description, r.scope, ", ".join(r.preconditions) or "-", probes,
                         code(r.rollback) if r.rollback else "-", r.duration_ticks])
        out.append(md_table(["id", "what it does", "scope", "preconditions", "verified by", "rollback", "ticks"], rows,
                            "llllllr"))
        out.append("")
    pairs = REGISTRY.rollback_pairs()
    out += ["## Rollback pairs\n",
            md_table(["runbook", "rolls back with"], [[code(a), code(b)] for a, b in pairs], "ll"), "",
            "## Playbooks (what the heuristic planner proposes)\n",
            "Steps run in order, one per verification cycle, each through the gate.\n",
            md_table(["fault", "steps"], [[code(f), " -> ".join(code(s) for s in steps)]
                                          for f, steps in PLAYBOOK.items()], "ll"), "",
            "Group incidents (several hosts, one shared cause) use these:\n",
            md_table(["hypothesis", "steps"], [[code(h), " -> ".join(code(s) for s in steps)]
                                               for h, steps in GROUP_PLAYBOOK.items()], "ll"), "",
            "## Known caveats\n",
            "- `restore_rack` and `undrain_host` return hosts to the scheduler without checking for faults; they are "
            "meant to follow a fix. The playbooks only emit them after a verified repair.\n"
            "- Rack-scope runbooks check preconditions on the proposed host only; the *gate* (not the runbook) "
            "checks every target host for protected roles and the drain cap.\n"]
    return "\n".join(out)


# ---- SCENARIOS.md -----------------------------------------------------------------------------------------


def scenario_rows() -> list[dict[str, Any]]:
    rows = []
    for name, s in load_scenarios().items():
        res = {}
        for who, approver in (("approve_all", approve_all), ("deny_all", deny_all)):
            summ = run_scenario(s, approver=approver).summary()
            res[who] = summ
        rows.append({"name": name, "scenario": s, "results": res})
    return rows


def scenarios_md() -> str:
    rows = scenario_rows()
    out = [GENERATED_NOTE, "# Scenario library\n",
           f"{len(rows)} named scenarios in `scenarios/*.json`, each validated against the scenario schema "
           "(`fleetgate.scenarios.SCENARIO_SCHEMA`) when loaded. A scenario is plain data: a fleet (size, seed, load "
           "pattern, topology), a timeline of fault events and a policy. Run one with "
           "`fleetgate simulate --scenario NAME`.\n",
           "The two result columns come from running every scenario here, seeded, with an approver that approves "
           "everything (`auto`) and one that rejects everything (`deny`): detected / resolved / contained count the "
           "faults the scenario injects; pages are escalations to a human. 'Resolved' means the fault was actually "
           "fixed; 'contained' means the host was safely drained but the fault remains for DC-ops. The same numbers "
           "are pinned as regression bounds in each scenario's `expect` block.\n",
           md_table(["scenario", "hosts", "ticks", "policy", "faults", "approve: det / res / con / pages",
                     "deny: det / res / con / pages"],
                    [[code(r["name"]), r["scenario"].fleet.get("hosts", 30), r["scenario"].ticks,
                      r["scenario"].policy, r["results"]["approve_all"]["faults_injected"],
                      _cells(r["results"]["approve_all"]), _cells(r["results"]["deny_all"])] for r in rows],
                    "lrrlrll"), "",
           "## What each scenario shows\n"]
    for r in rows:
        s = r["scenario"]
        out.append(f"### `{r['name']}`\n")
        out.append(f"{s.description}\n")
        faults = ", ".join(code(f) for f in s.faults) or "none"
        kinds = sorted({e["type"] for e in s.events if e["type"] != "inject"})
        extra = f"; group events: {', '.join(kinds)}" if kinds else ""
        out.append(f"- tags: {', '.join(s.tags)}; faults: {faults}{extra}\n")
    return "\n".join(out)


def _cells(s: dict[str, Any]) -> str:
    return f"{s['faults_detected']} / {s['faults_resolved']} / {s['faults_contained']} / {s['pages']}"


